-- 0003_cnae_segments — CNAE → segment map (gap G6, task B6).
--
-- POC 1 classifies tender *items* into 14 segments by NCM and keyword. Nothing
-- mapped a *company's* CNAEs onto those segments, so "Compatível / Verificar"
-- (spec §10) could not be computed. This is that bridge.
--
-- Production reference data, like 0002_plan_limits: it ships as a migration so
-- every environment has it, not as a dev fixture.
--
-- The rows below are generated from `db/reference/cnae_segments.csv`, which is
-- the artefact people read and review. Never hand-edit the generated block:
-- edit the CSV and re-render (`db/README.md` → "The CNAE → segment map").

create table if not exists cnae_segments (
  cnae    text not null,                    -- IBGE CNAE 2.3 subclass, 7 digits,
                                            -- zero-padded exactly as `companies.main_cnae`
                                            -- and `companies.secondary_cnaes` store it (B5).
  segment text not null,                    -- one of POC 1's 14 segments
  fit     text not null,                    -- compatible | check
  note    text,                             -- why, when the mapping is not self-evident
  primary key (cnae, segment),
  constraint cnae_segments_cnae_check check (cnae ~ '^[0-9]{7}$'),
  constraint cnae_segments_fit_check  check (fit in ('compatible','check')),
  constraint cnae_segments_segment_check check (segment in (
    'Alimentos',
    'Construção / Hidráulica',
    'Elétrica',
    'Esportes / Lazer',
    'Ferragens / Ferramentas',
    'Gráfico / Escritório',
    'Informática / TI',
    'Limpeza / Higiene',
    'Mobiliário',
    'Saúde / Hospitalar',
    'Segurança Eletrônica / CFTV',
    'Software / Sistemas',
    'Veículos / Peças',
    'Vestuário / Uniformes'
  ))
);

create index if not exists cnae_segments_segment_idx on cnae_segments (segment, fit);

-- A company's segments, with the fit the Radar badge shows.
--
-- **`compatible` requires the main CNAE.** A segment reached only through
-- secondary CNAEs is capped at `check`, however the map rates that pair, and a
-- `compatible` secondary therefore never lifts a `check` primary.
--
-- That is not the obvious rule, and it is not the one this task shipped first.
-- The obvious rule is "fit belongs to the (CNAE, segment) pair, take the
-- strongest claim" — habilitação does look at the registered object as a whole,
-- and a secondary CNAE is as registered as the primary one. Measured over 20
-- real PNCP-winning suppliers it gave each company a mean of **5.75 of the 14
-- segments as compatible**, one of them 13 of 14. Small companies register
-- broad secondary lists their accountant chose, not activities they trade in,
-- so a badge that unions over them says "Compatível" to everything and stops
-- meaning anything. The same 20 under this rule: mean 0.8, never above 1.
--
-- The secondary CNAEs are not discarded — they still put the segment on the
-- list, at `check`, which is exactly "you have a CNAE for this, verify it".
-- `from_main_cnae` / `from_secondary_cnae` say which path was taken, so the
-- Radar can sort the main activity first.
create or replace view company_segments as
with company_cnae as (
  select cnpj, main_cnae as cnae, true as is_main
    from companies
   where main_cnae is not null
  union all
  select c.cnpj, s.cnae, false
    from companies c, unnest(coalesce(c.secondary_cnaes, '{}'::text[])) as s(cnae)
)
select cc.cnpj,
       m.segment,
       case
         when bool_or(m.fit = 'compatible' and cc.is_main) then 'compatible'
         else 'check'
       end as fit,
       bool_or(cc.is_main)     as from_main_cnae,
       bool_or(not cc.is_main) as from_secondary_cnae
  from company_cnae cc
  join cnae_segments m on m.cnae = cc.cnae
 group by cc.cnpj, m.segment;

