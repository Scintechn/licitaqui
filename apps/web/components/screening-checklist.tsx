import type { ReactNode } from 'react'
import { Icon, SectionLabel } from '@/components'
import { format, messages } from '@/lib/messages'
import type { Checklist, ChecklistKey } from '@/lib/radar/contract'

const screeningCopy = messages.radar.screening
const opportunityCopy = messages.radar.opportunity
const fieldsCopy = messages.radar.fields
const valuesCopy = messages.radar.values

/**
 * The ScreeningChecklist component — canvas 11, two blocks (D27).
 *
 * Replaces the broken meter ("3 de 4" → "5 de 7" goes backwards) with two
 * separate, always-visible blocks that show what a deep analysis purchase
 * reveals. The only artefact in the product that shows a reader what their
 * triagem bought.
 *
 * ## Why two blocks and not one
 *
 * "Por que este edital apareceu para você" is a claim about the **matcher** —
 * structured PNCP fields, permanent. What the triagem finds is a claim about
 * the **edital text** — probabilistic, page-cited, revisable. Mutating one
 * heading between two meanings is how a reader concludes the first answer was
 * wrong; so two headings, discriminated on the checklist's provenance field,
 * with the PNCP block collapsing to one summary line above the AI block
 * rather than disappearing.
 *
 * ## Why the denominator does not move
 *
 * Every key is present at every moment. A triagem turns `unknown` rows into
 * answers, but the denominator stays the same (10 keys, always). This shows a
 * reader what they would be buying: seven rows that currently say nothing.
 *
 * ## Exception counts, never percentages
 *
 * A count can only rise as the product learns more, which is the behaviour
 * the meter got backwards. Exception counts take visual priority.
 *
 * ## States and the blocker gap
 *
 * Only two states ship today: `ok` and `unknown`. The `blocker` state is
 * declared but nothing emits it yet (D35). Until then, the headline reads
 * "0 exigências podem te barrar" on every tender — a sentence generated by a
 * gap rather than by a reading, which is the exact shape CLAIMS.md exists for.
 *
 * ## The `spent` gate
 *
 * §3.2 shares an analysis across users and §10 allocates it per user, so a
 * tender somebody else paid to read is unread for this viewer — and the page
 * numbers in it were bought with somebody else's triagem. D27's card states
 * the rule: "gate on `spent`, not `ready`".
 */

export interface ScreeningChecklistProps {
  checklist: Checklist
  score: number | null
  spent: boolean
}

/**
 * Render a single checklist row.
 */
function ChecklistRowItem({
  checklistKey,
  state,
  page,
  pageUnverified,
}: {
  checklistKey: ChecklistKey
  state: 'ok' | 'unknown'
  page: number | null
  pageUnverified: boolean
}) {
  const label = fieldsCopy[checklistKey]

  const stateText = state === 'ok' ? valuesCopy.notRequired : valuesCopy.unknown

  return (
    <li className="flex items-start gap-2.5 text-body">
      {state === 'ok' ? (
        <Icon name="check" size={16} strokeWidth={2.4} className="mt-1 text-success shrink-0" />
      ) : (
        <span className="mt-1 text-muted shrink-0">—</span>
      )}
      <div className="flex flex-col gap-0.5 min-w-0">
        <span className="font-medium">{label}</span>
        <span className="text-meta text-muted">{stateText}</span>
        {page !== null && (
          <span className="text-meta text-muted">
            {pageUnverified ? screeningCopy.pageUnverified : format(screeningCopy.page, { numero: page })}
          </span>
        )}
      </div>
    </li>
  )
}

/**
 * The PNCP block — permanent, always visible.
 * Collapses to one summary line above the AI block.
 */
function PncpBlock({ checklist }: { checklist: Checklist }) {
  const pncpRows = checklist.rows.filter((row) => row.source === 'pncp')
  const checkedCount = pncpRows.filter((row) => row.state === 'ok').length

  if (pncpRows.length === 0) return null

  return (
    <section className="flex flex-col gap-2">
      <SectionLabel tone="muted">{opportunityCopy.whyTitle}</SectionLabel>
      <div className="rounded-[10px] bg-blue-soft px-3 py-2.5">
        <p className="m-0 text-body text-blue">
          {checkedCount} de {pncpRows.length}{' '}
          {checkedCount === 1 ? 'requisito PNCP atendido' : 'requisitos PNCP atendidos'}
        </p>
      </div>
      <details className="group">
        <summary className="cursor-pointer list-none [&::-webkit-details-marker]:hidden flex items-center gap-1.5 text-body text-blue font-medium min-h-touch">
          <Icon name="chevronRight" size={14} className="transition-transform group-open:rotate-90" />
          <span>{checkedCount === pncpRows.length ? 'Tudo verificado' : 'Ver detalhes'}</span>
        </summary>
        <ul className="m-0 mt-2 flex list-none flex-col gap-2 p-0">
          {pncpRows.map((row) => (
            <ChecklistRowItem
              key={row.key}
              checklistKey={row.key}
              state={row.state === 'ok' ? 'ok' : 'unknown'}
              page={row.page}
              pageUnverified={row.pageUnverified}
            />
          ))}
        </ul>
      </details>
    </section>
  )
}

/**
 * The AI block — gated on `spent`.
 * Shows findings from the deep analysis.
 */
function AiBlock({
  checklist,
  score,
  spent,
}: {
  checklist: Checklist
  score: number | null
  spent: boolean
}) {
  if (!spent) return null

  const aiRows = checklist.rows.filter((row) => row.source === 'ai')

  if (aiRows.length === 0) return null

  const unknownCount = aiRows.filter((row) => row.state === 'unknown').length
  const checkedCount = aiRows.filter((row) => row.state === 'ok').length

  // Exception counts lead
  const exceptionText =
    unknownCount === 1 ? '1 coisa para você conferir' : `${unknownCount} coisas para você conferir`

  return (
    <section className="flex flex-col gap-2">
      <SectionLabel tone="muted">{opportunityCopy.aiBlockTitle}</SectionLabel>

      {/* Exception counts row, leading */}
      {unknownCount > 0 && (
        <div className="rounded-[10px] bg-attention-soft px-3 py-2.5">
          <p className="m-0 text-body text-attention">{exceptionText}</p>
        </div>
      )}

      {/* Checked rows list */}
      {checkedCount > 0 && (
        <div>
          <p className="text-caption text-muted mb-2">
            {checkedCount === 1 ? '1 ponto conferido' : `${checkedCount} pontos conferidos`}
          </p>
          <ul className="m-0 flex list-none flex-col gap-2 p-0">
            {aiRows
              .filter((row) => row.state === 'ok')
              .map((row) => (
                <ChecklistRowItem
                  key={row.key}
                  checklistKey={row.key}
                  state="ok"
                  page={row.page}
                  pageUnverified={row.pageUnverified}
                />
              ))}
          </ul>
        </div>
      )}

      {/* Unknown rows */}
      {unknownCount > 0 && (
        <div>
          <p className="text-caption text-muted mb-2">
            {unknownCount === 1 ? '1 ponto sem resposta' : `${unknownCount} pontos sem resposta`}
          </p>
          <ul className="m-0 flex list-none flex-col gap-2 p-0">
            {aiRows
              .filter((row) => row.state === 'unknown')
              .map((row) => (
                <ChecklistRowItem
                  key={row.key}
                  checklistKey={row.key}
                  state="unknown"
                  page={row.page}
                  pageUnverified={row.pageUnverified}
                />
              ))}
          </ul>
        </div>
      )}

      {/* Score badge row with label */}
      {score !== null && (
        <div className="rounded-[10px] border border-line-strong bg-surface px-3 py-2.5 flex items-center justify-between">
          <span className="text-caption text-muted">{screeningCopy.verdict.scoreLabel}</span>
          <span className="text-body font-medium">
            {score} {screeningCopy.verdict.scoreOf}
          </span>
        </div>
      )}

      {/* Provenance signal in header */}
      <p className="text-caption text-muted">
        {messages.ai.disclaimer} {messages.ai.notLegalAdvice}
      </p>
    </section>
  )
}

/**
 * The ScreeningChecklist component.
 *
 * Two blocks: PNCP (always visible) and AI (gated on spent).
 * Lead with exception counts, show checked rows, make unknown explicit.
 */
export function ScreeningChecklist({
  checklist,
  score,
  spent,
}: ScreeningChecklistProps): ReactNode {
  return (
    <div className="@container">
      <div className="flex flex-col gap-7 pt-7 @min-[860px]:grid @min-[860px]:grid-cols-2 @min-[860px]:items-start @min-[860px]:gap-10">
        <PncpBlock checklist={checklist} />
        <AiBlock checklist={checklist} score={score} spent={spent} />
      </div>
    </div>
  )
}
